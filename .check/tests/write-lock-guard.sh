#!/usr/bin/env bash
# 写权锁的**起手守卫** —— 单独一个文件。
#
# 为什么必须单独成文件：自测要验证「守卫对过期锁会清、对活锁会拒跑」，
# 唯一办法是**再调一次守卫**。而守卫原先住在 `write-lock-test.sh` 里，
# 于是「调守卫」= 「跑整份测试」= **递归**。
# 第一版就是这样翻车的：守卫按**名字**放行（`selftest:` 前缀 = 自己上次的残留，可以清），
# 而守卫自己那把锁也叫 `selftest:guard` —— 内层于是**不拒跑**，直接再跑一遍整份测试，
# 跑到自指项又递归一次。实测 **112 个嵌套 bash 进程、每 3.3 秒长一层**（ISS-070）。
# 抽出来之后：守卫是**唯一实现**（测试调它、不重写它），递归**在结构上不可能**。
#
# 用法：`bash .check/tests/write-lock-guard.sh`
# 退出码：`0` 可以继续（无锁 / 已清掉过期锁 / 已清掉读不出持有者的文件）
#         `2` **拒跑**（有人正持有未过期的锁，或状态读不出来）
#
# 【规则只有一条 · 2026-09-16 · ISS-060 → ISS-070】
#   **「已过期」是允许清的唯一理由，名字不参与判定。**
#     持有者活着（未过期）        → 拒跑 rc=2（无论它叫什么名字）
#     已过期                      → 清掉（它本来就会被下一个取锁者抢占）
#     存在但读不出持有者（0 字节等）→ 也走上面这一支：`write-lock.js` 把它判成「已过期」
#                                    （一个读不出持有者的文件不提供任何互斥信息，ISS-071）
#   判定读的就是 `write-lock.js status` 打印的 `已过期=` 字段 ——
#   **同一条规则不实现两遍**（同 ISS-007：两份实现会互相背书，且不一致的方向是静默的）。
#   命名空间（`selftest:`）保留，但**只用于人读**，不再参与判定。
#
# 【为什么名字不能当通行证】
#   ① 它和「拒绝进」的守卫规则写在同一个前缀上，两条规则必然打架 —— 第一版就是（递归）。
#   ② 并发下它会删掉别人的**活锁**：同一份测试若被跑两次（本项目实测过一条命令被执行两次），
#      后一份会把前一份正在用的 `selftest:testA` 当成「自己上次的残留」清掉 ——
#      ISS-060 的伤害原样回来，只是换了个触发方式。
#
# 【失败方向必须是「拒跑」】
#   只有**明确读到**「已过期=是」或「没有锁」才清；其它一切情形一律拒跑。
#   反过来的写法（「读到『未过期』才拒跑」）在 status 输出格式一变时会**变成「什么都清」** ——
#   那正是 ISS-060 的形状，而且是静默的。
#
# 【为什么 TTL 必须短】按「过期才清」，一次被中断的运行留下的锁会挡住下一轮
#   **直到它声明的 TTL 到期**。所以 `write-lock-test.sh` 给自己声明的 TTL 一律 **5 分钟**
#   （实测整份测试约 3 秒跑完，余量 ~100×）：最坏恢复时间从 30 分钟降到 5 分钟。
#   **不引入任何「跳过守卫」的开关**（DEC-023）。
set -u
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT" || exit 2

if [ ! -e .check/.write-lock ]; then exit 0; fi

HOLD=$(sed -n '1p' .check/.write-lock 2>/dev/null | awk '{print $1}')
ST=$(node .check/write-lock.js status 2>&1)

if echo "$ST" | grep -q '已过期=是'; then
  echo "NOTE  起手发现**已过期**的锁（holder=$HOLD）→ 清掉（下一个取锁者本来也会抢占它）"
  rm -f .check/.write-lock .check/.write-lock.takeover
  exit 0
fi

if echo "$ST" | grep -q '^LOCK free'; then
  # 走到这里只可能是**竞态**：`-e` 为真、随后文件就没了（或被删/被放掉）。
  # 0 字节那种「读不出持有者」的情形**不在这里** —— `write-lock.js` 现在把它判成
  # `已过期=是`（一个读不出持有者的文件不提供任何互斥信息），走上面那一支。
  echo "NOTE  锁文件在检查期间消失了（$(wc -c < .check/.write-lock 2>/dev/null | tr -d ' ') 字节残留）→ 清掉残留"
  rm -f .check/.write-lock .check/.write-lock.takeover
  exit 0
fi

echo "SKIP  写权锁自测**拒跑**：有人正持有锁（holder=$HOLD，未过期）。"
echo "      本测试与生产**共用同一把锁文件**，跑它会删掉别人的锁（ISS-060）。"
echo "      要么等它释放，要么等它的 TTL 到期（到期后守卫会自己清掉）。"
echo "$ST" | sed 's/^/      /'
exit 2
