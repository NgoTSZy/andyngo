#!/usr/bin/env bash
# 记录层的**幂等追加** —— 给 `newid.js` 加一层「写过就不重复写」的壳。
#
# 为什么必须有（2026-09-16 · ISS-068 → ISS-075 → ISS-077 → ISS-079）：
# 本会话实测**一条命令可能被执行两次**（命令带 `⚠️ Sandbox bypassed (escalation-approved)`
# 提示 = 「先被沙箱拦下 → 等批准 → 以 bypass 重跑」），而**两次的副作用都落了盘**。
# 于是每一次追加都可能变成**两行逐字相同**的记录。已实测的重复对：**7 对**
# （`ISS-060≡061` · `064≡065` · `066≡067` · `068≡069` · `070≡071` · `075≡076` · `077≡078`，
#  外加 `DEC-032≡033` · `CHG-092≡093`）。**号没重、号没缺，坏的是「号 → 内容」的唯一性**
# （DEC-026「『没丢东西』不等于『没坏』」）。
#
# 为什么是**机制**而不是**纪律**：先试过两条纪律 ——「分配前 `rm -f` 残留锁」和
# 「分配后核对号与正文」—— **两次都在做了这两条之后照样发生**（核对只对了末行号，
# 看不出整体位移）。纪律依赖「我记得」，机制不依赖。
#
# 为什么查重能防住：**两次执行读的是同一个正文文件**（同一条命令、同一个 `@路径`），
# 所以第二次执行一定能命中「这段正文已经在文件里」。命中就跳过 —— **写入因此幂等**。
#
# 用法：
#   bash .check/record/alloc.sh <记录文件> <前缀> <分隔符> <@正文文件>
# 例：
#   bash .check/record/alloc.sh .check/record/issues.md ISS - @C:/.../.check/tmp/iss079.txt
#
# 退出码：0 已写入 **或** 已存在（跳过）· 2 参数/路径错 · 3/4/5/6 透传 `newid.js`
set -u
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT" || exit 2

if [ $# -ne 4 ]; then
  echo "用法: bash .check/record/alloc.sh <记录文件> <前缀> <分隔符> <@正文文件>"
  exit 2
fi
f="$1"; p="$2"; s="$3"; ref="$4"
case "$ref" in
  @*) b="${ref#@}" ;;
  *) echo "正文必须是 @文件 形式（含反引号/引号的正文内联进命令行会被 shell 吃掉片段，ISS-048）"; exit 2 ;;
esac
if [ ! -f "$b" ]; then echo "正文文件不存在: $b"; exit 2; fi
if [ ! -f "$f" ]; then echo "记录文件不存在: $f"; exit 2; fi

BODY="$(cat "$b")"
if [ -z "$BODY" ]; then echo "正文是空的，拒写"; exit 2; fi

# 【2026-09-17 加，W23 J18 · ISS-137】**写端护栏：EVT 的 ts 必须带秒。**
# 为什么必须有：`andyngo-integrity.js` 的 **I4** 要求 eventlog 的 ts 形如
# `YYYY-MM-DDThh:mm:ss[.sss]Z`，而 **CHG / ISS / DEC 是分钟精度**（`…Thh:mmZ`）——
# **两种精度同时存在**，而我在**同一会话里踩了两次**（EVT 007、EVT 008 都写成 `…Thh:mmZ`）。
# 两次都是**判据（I4）抓到的**，但 **I4 是读端**：它抓到时坏行**已经落盘**，只能就地改行
# （先例 CHG-165 / CHG-184 就是两次「EVT ts 补秒」）。**护栏要两端都有**（ISS-129 的同一条纪律）：
# 写端 `andy-record.sh` 有字段数护栏、读端 `andy-dream.sh` 有格式护栏 ——
# 而「落记录层」这条路（`alloc.sh`）**此前没有任何形状护栏**。
# 这里补的就是它：**EVT 的 ts 不带秒 → rc=2 拒跑，一个字节都不写。**
# ★ 只对 `EVT` 生效：CHG / ISS / DEC **必须**保持分钟精度，拦它们会拦错。
if [ "$p" = "EVT" ]; then
  ts0=$(awk 'NR==1{print $1}' "$b" | tr -d '\r')
  if ! printf '%s' "$ts0" | grep -Eq '^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}(\.[0-9]+)?Z$'; then
    echo "REJECT EVT 的 ts 必须带秒（YYYY-MM-DDThh:mm:ssZ），实际是 \`$ts0\` ——"
    echo "       **CHG / ISS / DEC 才是分钟精度**（ISS-137）。拒跑，一个字节都不写。"
    exit 2
  fi
fi

# 查重：正文已在文件里 → 说明这条命令被执行过（或正文被复用）→ 不重复追加。
# `-F` 按字面匹配（正文里有 `【】`、反引号、`|` 等），`--` 防止正文以 `-` 开头被当选项。
#
# ★ 2026-09-17 修（ISS-125）：查重**必须用「落盘时的那一个形态」**（`newid.js --flatten`），
#   不能用**原始**正文。理由（**实测复现**，不是推测）：
#   `grep -qF` 拿到**含换行**的 `$BODY` 时，按「**多行模式 = OR**」处理 ——
#   正文里**任意一行**在文件中出现就判「已写过」→ `rc=0` 跳过 →
#   **一条全新记录被静默丢弃**（**行数不变、没有任何红**）。实测：正文第 2 行恰好是
#   文件里某行的子串时复现。而 ISS-125 原文写的那个方向（「重复追加」）**没有复现** ——
#   因为正文首行总是折行后记录的前缀，OR 语义总会命中。
#   **丢记录比重复更坏**：重复看得见（行数多 1），丢记录是**静默的**。
#   为什么调 `--flatten` 而不是在这里再写一遍 `tr '\n' ' '`：**复制会静默分叉** ——
#   落盘口径将来再改一次（ISS-124 就改过一次），第二份实现不会跟着改，两边又会对不上。
#   折行失败 → **拒写**（rc=2），**不许退回旧口径**：退回就等于把这条缺陷再打开一次。
FLAT="$(node .check/record/newid.js --flatten "@$b" 2>/dev/null)"; FRC=$?
if [ "$FRC" -ne 0 ] || [ -z "$FLAT" ]; then
  echo "REJECT 折行失败（rc=$FRC，或折行后为空）—— 查重无法在同口径下进行，拒写（ISS-125）"
  exit 2
fi
if grep -qF -- "$FLAT" "$f"; then
  echo "SKIP  正文已在该文件里（本命令被执行过两次）→ 不重复追加"
  exit 0
fi

# 只在真正要写的时候清**残留**锁。
#
# 【2026-09-16 · 本条自身的一个缺陷，实测抓到的】第一版写的是
# `rm -f .check/record/*.lock` —— 而 `eventlog/` 是**子目录**，
# 它的锁是 `.check/record/eventlog/2026-09-16.txt.lock`，**通配符够不到**。
# 后果实测：落 EVT 时 `newid.js` 报 `ALLOC-FAIL 锁超时（5s），未写入` rc=3 ——
# 而那个锁是 20 分钟前一次被杀的执行留下的 **0 字节**文件。
# 同族：**清理范围没覆盖「锁实际所在的位置」**（和 ISS-060「守卫删了别人的锁」是同一族：
# 都是「以为锁只在一个地方」）。
#
# 规则（比提示词现有的临时处置**更窄**，且与 `readLock` 对 0 字节的处置一致，ISS-072）：
#   **只清 0 字节的 `*.lock`** —— 0 字节的锁文件**不提供任何互斥信息**，它不是锁。
#   （`newid.js` 的锁是「先 O_EXCL 建、再写内容」，进程在两步之间被杀就留下 0 字节文件。）
# 残留的竞态窗口是**微秒级**；而旧行为是**静默白等 5 秒然后 rc=3**，严格更差。
# **没有**用「全量 `rm -f`」（提示词 §0.2 的临时处置）：那会删掉别人**正在持有**的锁。
# 真正的根治在 ISS-063（`newid.js` 自己判陈旧），本轮未动 `newid.js`。
find .check/record -name '*.lock' -size 0 -delete 2>/dev/null
out=$(node .check/record/newid.js "$f" "$p" "$s" "@$b" 2>&1); rc=$?
echo "$out"
exit "$rc"
